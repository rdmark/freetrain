import { expect, test } from '@playwright/test';

test('delayed/rejected commands, inspectors, reconnect and bilingual drafts', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByTestId('connection')).toHaveText('Connected to fixture');
  await expect(page.getByRole('heading', { name: 'Reference world' })).toBeVisible();
  await page.getByLabel('Fixture response').selectOption('delayed');
  await page.getByRole('button', { name: 'Run', exact: false }).click();
  await expect(page.getByRole('status')).toHaveText('Waiting for fixture confirmation…');
  await expect(page.getByTestId('clock-state')).toHaveText('Paused');
  await expect(page.getByRole('button', { name: 'Single step', exact: false })).toBeDisabled();
  await expect(page.getByTestId('clock-state')).toHaveText('Running');
  await page.getByLabel('Fixture response').selectOption('normal');
  await page.getByRole('button', { name: 'Pause', exact: false }).click();
  await expect(page.getByTestId('clock-state')).toHaveText('Paused');
  await page.getByRole('combobox', { name: 'Controller', exact: true }).selectOption('manual');
  await expect(page.getByRole('status')).toHaveText('Confirmed by fixture');
  await expect(page.getByRole('combobox', { name: 'Controller', exact: true })).toHaveValue('manual');
  await page.getByLabel('Fixture response').selectOption('rejected');
  await page.getByRole('combobox', { name: 'Controller', exact: true }).selectOption('automatic');
  await expect(page.getByRole('status')).toContainText('Fixture rejected');
  await expect(page.getByRole('combobox', { name: 'Controller', exact: true })).toHaveValue('manual');
  await page.getByLabel('Station name', { exact: true }).fill('新宿駅');
  await page.getByRole('button', { name: 'Apply name', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Fixture rejected');
  await expect(page.getByTestId('confirmed-name')).toHaveText('中央駅');
  await expect(page.getByLabel('Station name', { exact: true })).toHaveValue('新宿駅');
  await page.getByLabel('Fixture response').selectOption('normal');
  await page.getByRole('button', { name: 'Apply name', exact: true }).click();
  await expect(page.getByTestId('confirmed-name')).toHaveText('新宿駅');
  await page.getByLabel('Fixture response').selectOption('delayed');
  await page.getByRole('button', { name: 'Single step', exact: false }).click();
  await page.getByRole('button', { name: 'Reconnect fixture' }).click();
  await expect(page.getByTestId('connection')).toHaveText('Connecting…');
  await expect(page.getByTestId('connection')).toHaveText('Connected to fixture');
  await expect(page.getByTestId('confirmed-name')).toHaveText('新宿駅');
  await expect(page.getByTestId('tick')).toHaveText('0');
  await page.getByLabel('Language').selectOption('ja');
  await expect(page.locator('html')).toHaveAttribute('lang', 'ja');
  await expect(page.getByRole('heading', { name: '列車情報' })).toBeVisible();
  await page.getByLabel('駅名', { exact: true }).fill('下書き');
  await page.getByRole('button', { name: '下書きを戻す' }).click();
  await expect(page.getByLabel('駅名', { exact: true })).toHaveValue('新宿駅');
  await page.screenshot({ path: `test-results/svelte-ja.png`, fullPage: true });
  await page.reload();
  await expect(page.getByLabel('駅名', { exact: true })).toHaveValue('中央駅');
  await expect(page.getByRole('heading', { name: '列車情報' })).toBeVisible();
  await page.getByLabel('言語').selectOption('en');
  await page.screenshot({ path: `test-results/svelte-en.png`, fullPage: true });
  expect(errors).toEqual([]);
});

test('composition, focus, selection and catalog scroll survive an incoming update', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByTestId('connection')).toHaveText('Connected to fixture');
  const catalog = page.getByRole('list', { name: 'Building catalog' });
  await expect(catalog.getByRole('button')).toHaveCount(40);
  await catalog.getByRole('button').last().focus();
  await page.keyboard.press('Enter');
  await expect(catalog.getByRole('button').last()).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByTestId('building-name')).toHaveText('Condominium 20');
  const scroll = await catalog.evaluate(el => ({ top: el.scrollTop, scrolls: el.scrollHeight > el.clientHeight }));
  expect(scroll.scrolls && scroll.top > 0).toBe(true);
  await page.getByLabel('Fixture response').selectOption('delayed');
  await page.getByRole('button', { name: 'Single step', exact: false }).click();
  const draft = page.getByLabel('Station name', { exact: true });
  await draft.fill('東京駅');
  await draft.focus();
  await draft.evaluate((el: HTMLInputElement) => {
    el.setSelectionRange(1, 2);
    el.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true, data: '東京駅' }));
  });
  const prevented = await draft.evaluate(el => !el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true, bubbles: true, cancelable: true })));
  expect(prevented).toBe(true);
  await page.keyboard.press('ArrowLeft');
  const selection = await draft.evaluate((el: HTMLInputElement) => [el.selectionStart, el.selectionEnd]);
  await expect(page.getByTestId('tick')).toHaveText('1');
  await expect(draft).toBeFocused();
  expect(await draft.evaluate((el: HTMLInputElement) => [el.selectionStart, el.selectionEnd])).toEqual(selection);
  await expect(draft).toHaveValue('東京駅');
  await expect(page.getByTestId('confirmed-name')).toHaveText('中央駅');
  await expect(page.getByRole('button', { name: 'Apply name', exact: true })).toBeDisabled();
  expect(await catalog.evaluate(el => el.scrollTop)).toBe(scroll.top);
  await draft.dispatchEvent('compositionend', { data: '東京駅' });
  await expect(page.getByRole('button', { name: 'Apply name', exact: true })).toBeEnabled();
  await page.getByLabel('Fixture response').selectOption('normal');
  await draft.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByTestId('confirmed-name')).toHaveText('東京駅');
});

test('Japanese labels and keyboard controls fit narrow and doubled-density layouts', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 640, height: 450 }, deviceScaleFactor: 2, locale: 'ja-JP' });
  const page = await context.newPage();
  await page.goto('/');
  await expect(page.getByTestId('connection')).toHaveText('サンプルに接続済み');
  for (const width of [720, 640, 360]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  const input = page.getByLabel('駅名', { exact: true });
  await input.focus();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: '駅名を適用', exact: true })).toBeFocused();
  await page.screenshot({ path: `test-results/svelte-ja-narrow-2x.png`, fullPage: true });
  await context.close();
});
